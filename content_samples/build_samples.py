def H(*texts):
    return [{"level": i + 1, "text": t} for i, t in enumerate(texts)]


def ch(key, prompt, options, correct, hints, diff=1, sol=None, est=30):
    return {"key": key, "type": "single_choice", "difficulty": diff, "est_seconds": est,
            "payload": {"prompt": prompt, "options": [{"id": chr(97 + i), "text": o} for i, o in enumerate(options)],
                        "hints": H(*hints), "solution_steps": sol or []},
            "answer": {"correct": [chr(97 + options.index(correct))]}}


def num(key, prompt, value, hints, diff=1, sol=None, typ="number_input", est=40, distr=None):
    return {"key": key, "type": typ, "difficulty": diff, "est_seconds": est,
            "payload": {"prompt": prompt, "hints": H(*hints), "solution_steps": sol or [],
                        "distractor_feedback": distr or {}},
            "answer": {"value": value}}


def frac(key, prompt, value, hints, model=None, diff=1, sol=None, distr=None, reduced=False):
    p = {"prompt": prompt, "hints": H(*hints), "solution_steps": sol or [], "distractor_feedback": distr or {}}
    if model:
        p["model"] = model
    return {"key": key, "type": "fraction_input", "difficulty": diff, "est_seconds": 45,
            "payload": p, "answer": {"value": value, "require_reduced": reduced}}


def cat(key, prompt, buckets, items, answer, hints, diff=2):
    return {"key": key, "type": "categorize", "difficulty": diff, "est_seconds": 60,
            "payload": {"prompt": prompt, "buckets": [{"id": b, "title": t} for b, t in buckets],
                        "items": [{"id": str(i), "text": str(i)} for i in items], "hints": H(*hints)},
            "answer": {"buckets": {b: [str(x) for x in v] for b, v in answer.items()}}}


def order(key, prompt, items, correct, hints, diff=2):
    return {"key": key, "type": "drag_order", "difficulty": diff, "est_seconds": 50,
            "payload": {"prompt": prompt, "items": [{"id": i, "text": t} for i, t in items], "hints": H(*hints)},
            "answer": {"order": correct}}


def match(key, prompt, pairs, hints, diff=1):
    return {"key": key, "type": "matching", "difficulty": diff, "est_seconds": 60,
            "payload": {"prompt": prompt, "left": [{"id": f"l{i}", "text": a} for i, (a, b) in enumerate(pairs)],
                        "right": [{"id": f"r{i}", "text": b} for i, (a, b) in enumerate(pairs)], "hints": H(*hints)},
            "answer": {"pairs": {f"l{i}": f"r{i}" for i in range(len(pairs))}}}


def steps(key, prompt, st, hints, model=None, diff=2):
    p = {"prompt": prompt, "steps": st, "hints": H(*hints)}
    if model:
        p["model"] = model
    return {"key": key, "type": "step_by_step", "difficulty": diff, "est_seconds": 120,
            "payload": p, "answer": {"steps": [{"answer": s["answer"]} for s in st]}}


