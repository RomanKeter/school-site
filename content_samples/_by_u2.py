from _by_lib import NUM, PU, SC, skill, topic, unit

PURP = ["апавядальны", "пытальны", "пабуджальны"]


def pur(text, right, extra=""):
    return SC(f"Вызнач від сказа па мэце выказвання: «{text}»", right, [p for p in PURP if p != right],
              {"апавядальны": "Сказ паведамляе пра нешта — апавядальны.",
               "пытальны": "Сказ мае пытанне — пытальны.",
               "пабуджальны": "Сказ заклікае да дзеяння, мае просьбу ці загад — пабуджальны."}[right] + extra)


def endmark(text, right, why):
    return SC(f"Які знак патрэбны ў канцы: «{text}…»?", right, [m for m in ("кропка", "пытальнік", "клічнік") if m != right], why)


def member(sent, word, right, why):
    return SC(f"Якім членам сказа з'яўляецца слова «{word}»: «{sent}»?", right,
              [m for m in ("дапаўненне", "азначэнне", "акалічнасць") if m != right], why)


def dash(pair, need, right_text, why):
    return SC(f"Ці патрэбны працяжнік: «{pair}»?", "так" if need else "не", ["не" if need else "так"],
              (f"Правільна: «{right_text}». " if need else "") + why)


def ext(sent, developed):
    return SC(f"Які гэта сказ: «{sent}»?", "развіты" if developed else "неразвіты", ["неразвіты" if developed else "развіты"],
              "Ёсць даданыя члены — развіты сказ." if developed else "Толькі дзейнік і выказнік — неразвіты сказ.")


