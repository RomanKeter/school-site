def syn(word, right, wrong, kind="сінонім"):
    return SC(f"Падбяры {kind} да слова «{word}»", right, wrong,
              f"{word.capitalize()} — {right}: " + ("словы блізкія па значэнні." if kind == "сінонім" else "словы з процілеглым значэннем."))


def idiom(phrase, right, wrong):
    return SC(f"Што азначае фразеалагізм «{phrase}»?", right, wrong, f"«{phrase}» — {right}.")


