def hints(*texts):
    return [{"level": i + 1, "text": t} for i, t in enumerate(texts)]


def ch(key, prompt, options, correct, hs, difficulty=1, verify=None, seconds=30):
    opts = [{"id": str(i), "text": t} for i, t in enumerate(options)]
    if isinstance(correct, str):
        idx = options.index(correct)
    else:
        idx = correct
    return {
        "key": key, "type": "single_choice", "difficulty": difficulty, "est_seconds": seconds,
        "payload": {"prompt": prompt, "options": opts, "hints": hints(*hs)},
        "answer": {"correct": [str(idx)]},
        "verify": verify or {"op": "choice_text", "text": options[idx]},
    }


def num(key, prompt, value, hs, difficulty=1, verify=None, seconds=30, tolerance=0):
    ans = {"value": str(value)}
    if tolerance:
        ans["tolerance"] = tolerance
    return {
        "key": key, "type": "number_input", "difficulty": difficulty, "est_seconds": seconds,
        "payload": {"prompt": prompt, "hints": hints(*hs)},
        "answer": ans,
        "verify": verify or {"op": "eq", "value": value},
    }


def txt(key, prompt, value, hs, difficulty=1, accept=None, verify=None, seconds=30):
    acc = list(accept or [value])
    return {
        "key": key, "type": "text_input", "difficulty": difficulty, "est_seconds": seconds,
        "payload": {"prompt": prompt, "hints": hints(*hs)},
        "answer": {"value": value, "accept": acc},
        "verify": verify or {"op": "text", "accept": acc},
    }


def match(key, prompt, pairs, hs, difficulty=1, verify=None, seconds=50):
    left = [{"id": f"l{i}", "text": a} for i, (a, _) in enumerate(pairs)]
    right = [{"id": f"r{i}", "text": b} for i, (_, b) in enumerate(pairs)]
    # shuffle right ids visually? keep r_i aligned; UI shuffles. Fine.
    return {
        "key": key, "type": "matching", "difficulty": difficulty, "est_seconds": seconds,
        "payload": {"prompt": prompt, "left": left, "right": right, "hints": hints(*hs)},
        "answer": {"pairs": {f"l{i}": f"r{i}" for i in range(len(pairs))}},
        "verify": verify or {"op": "pairs", "pairs": [[a, b] for a, b in pairs]},
    }


def order(key, prompt, items, hs, difficulty=2, verify=None, seconds=50):
    ids = [f"i{i}" for i in range(len(items))]
    return {
        "key": key, "type": "drag_order", "difficulty": difficulty, "est_seconds": seconds,
        "payload": {"prompt": prompt, "items": [{"id": i, "text": t} for i, t in zip(ids, items)],
                    "hints": hints(*hs)},
        "answer": {"order": ids},
        "verify": verify or {"op": "order", "items": list(items)},
    }


def cat(key, prompt, buckets, hs, difficulty=2, verify=None, seconds=60):
    # buckets: list[(title, [item_texts])]
    bmeta, items, ans, vmap = [], [], {}, {}
    n = 0
    for bi, (title, members) in enumerate(buckets):
        bid = f"b{bi}"
        bmeta.append({"id": bid, "title": title})
        ans[bid] = []
        for m in members:
            iid = f"x{n}"
            n += 1
            items.append({"id": iid, "text": m})
            ans[bid].append(iid)
            vmap[m] = title
    return {
        "key": key, "type": "categorize", "difficulty": difficulty, "est_seconds": seconds,
        "payload": {"prompt": prompt, "buckets": bmeta, "items": items, "hints": hints(*hs)},
        "answer": {"buckets": ans},
        "verify": verify or {"op": "buckets", "map": vmap},
    }


def skill(key, title, rule, example_title, steps, exercises, prereq=None, order=0, desc=""):
    assert 15 == len(exercises), (key, len(exercises))
    keys = [e["key"] for e in exercises]
    assert len(keys) == len(set(keys)), key
    return {
        "key": key, "title": title, "description": desc,
        "rule_card": rule,
        "worked_example": {"title": example_title, "steps": steps},
        "prerequisites": prereq or [],
        "order": order,
        "exercises": exercises,
    }


def unit(key, title, quarter, order, topic_key, topic_title, synonyms, keywords, skills, refs=""):
    return {
        "subject": "cim",
        "unit": {"key": key, "title": title, "grade": 5, "quarter": quarter, "order": order},
        "topics": [{
            "key": topic_key, "title": topic_title, "description": "",
            "badge_code": "", "synonyms": synonyms, "keywords": keywords,
            "textbook_refs": [refs] if refs else [],
            "skills": skills,
        }],
    }



