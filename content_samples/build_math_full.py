def lcm(a: int, b: int) -> int:
    return abs(a * b) // _gcd(a, b)


def school_round(n: int, place: int) -> int:
    """Школьное округление неотрицательных: 0-4 вниз, 5-9 вверх."""
    q, r = divmod(n, place)
    if r >= place // 2:
        q += 1
    return q * place


def is_prime(n: int) -> bool:
    if n < 2:
        return False
    d = 2
    while d * d <= n:
        if n % d == 0:
            return False
        d += 1
    return True


def H(*texts):
    return [{"level": i + 1, "text": t} for i, t in enumerate(texts)]


def _v(ex, verify):
    if verify is not None:
        ex["verify"] = verify
    return ex


def ch(key, prompt, options, correct, hints, diff=1, sol=None, est=30, verify=None):
    return _v({
        "key": key, "type": "single_choice", "difficulty": diff, "est_seconds": est,
        "payload": {"prompt": prompt,
                    "options": [{"id": chr(97 + i), "text": str(o)} for i, o in enumerate(options)],
                    "hints": H(*hints), "solution_steps": sol or []},
        "answer": {"correct": [chr(97 + list(options).index(correct))]},
    }, verify)


def num(key, prompt, value, hints, diff=1, sol=None, typ="number_input", est=40, distr=None, verify=None):
    return _v({
        "key": key, "type": typ, "difficulty": diff, "est_seconds": est,
        "payload": {"prompt": prompt, "hints": H(*hints), "solution_steps": sol or [],
                    "distractor_feedback": distr or {}},
        "answer": {"value": str(value)},
    }, verify)


def frac(key, prompt, value, hints, model=None, diff=1, sol=None, distr=None, reduced=False, verify=None):
    p = {"prompt": prompt, "hints": H(*hints), "solution_steps": sol or [], "distractor_feedback": distr or {}}
    if model:
        p["model"] = model
    return _v({"key": key, "type": "fraction_input", "difficulty": diff, "est_seconds": 45,
               "payload": p, "answer": {"value": value, "require_reduced": reduced}}, verify)


def cat(key, prompt, buckets, items, answer, hints, diff=2, verify=None):
    return _v({
        "key": key, "type": "categorize", "difficulty": diff, "est_seconds": 60,
        "payload": {"prompt": prompt,
                    "buckets": [{"id": b, "title": t} for b, t in buckets],
                    "items": [{"id": str(i), "text": str(i)} for i in items],
                    "hints": H(*hints)},
        "answer": {"buckets": {b: [str(x) for x in v] for b, v in answer.items()}},
    }, verify)


def order(key, prompt, items, correct, hints, diff=2, verify=None):
    return _v({
        "key": key, "type": "drag_order", "difficulty": diff, "est_seconds": 50,
        "payload": {"prompt": prompt, "items": [{"id": i, "text": t} for i, t in items],
                    "hints": H(*hints)},
        "answer": {"order": correct},
    }, verify)


def match(key, prompt, pairs, hints, diff=1, verify=None):
    return _v({
        "key": key, "type": "matching", "difficulty": diff, "est_seconds": 60,
        "payload": {"prompt": prompt,
                    "left": [{"id": f"l{i}", "text": a} for i, (a, b) in enumerate(pairs)],
                    "right": [{"id": f"r{i}", "text": b} for i, (a, b) in enumerate(pairs)],
                    "hints": H(*hints)},
        "answer": {"pairs": {f"l{i}": f"r{i}" for i in range(len(pairs))}},
    }, verify)


def steps(key, prompt, st, hints, model=None, diff=2, verify=None):
    p = {"prompt": prompt, "steps": st, "hints": H(*hints)}
    if model:
        p["model"] = model
    return _v({"key": key, "type": "step_by_step", "difficulty": diff, "est_seconds": 120,
               "payload": p, "answer": {"steps": [{"answer": s["answer"]} for s in st]}}, verify)


def skill(key, title, rule, example, exercises, prerequisites=None, order=0, description=""):
    s = {"key": key, "title": title, "description": description, "rule_card": rule,
         "worked_example": example, "exercises": exercises, "order": order}
    if prerequisites:
        s["prerequisites"] = prerequisites
    assert 8 <= len(exercises) <= 15, f"{key}: {len(exercises)} заданий, нужно 8–15 (добор или полный набор)"
    return s


def topic(key, title, skills, badge="", synonyms=None, keywords=None, refs=None, order=0, description=""):
    return {"key": key, "title": title, "description": description, "badge_code": badge,
            "synonyms": synonyms or [], "keywords": keywords or [],
            "textbook_refs": refs or [], "skills": skills, "order": order}


def dump(name, unit, topics):
    data = {"format_version": 1, "subject": "math", "unit": unit, "topics": topics}
    (OUT / name).write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    nsk = sum(len(t["skills"]) for t in topics)
    nex = sum(len(s["exercises"]) for t in topics for s in t["skills"])
    print(f"{name}: {nsk} навыков, {nex} заданий")


def we(title, *steps_):
    return {"title": title, "steps": list(steps_)}



