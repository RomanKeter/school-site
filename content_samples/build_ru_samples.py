def fl(key, d, before, after, opts, right, explain, hint, prompt="Вставь пропущенную букву"):
    """fill_letters: слово/предложение с пропуском; варианты — крупные кнопки."""
    return {"key": key, "type": "fill_letters", "difficulty": d, "est_seconds": 25,
            "payload": {"prompt": prompt, "parts": [before, after],
                        "options": [{"id": o, "text": o} for o in opts], "explain": explain,
                        "hints": [{"level": 1, "text": hint}]},
            "answer": {"correct": [right]}}


def sc(key, d, prompt, opts, right, explain, hint):
    return {"key": key, "type": "single_choice", "difficulty": d, "est_seconds": 30,
            "payload": {"prompt": prompt, "options": [{"id": f"o{i}", "text": t} for i, t in enumerate(opts)],
                        "explain": explain, "hints": [{"level": 1, "text": hint}]},
            "answer": {"correct": [f"o{opts.index(right)}"]}}


def cat(key, d, prompt, buckets, explain, hint):
    """buckets: {"название": [слова]} — id слова = само слово."""
    items, ans, bl = [], {}, []
    for i, (title, words) in enumerate(buckets.items()):
        bid = f"b{i}"
        bl.append({"id": bid, "title": title})
        ans[bid] = list(words)
        items += [{"id": w, "text": w} for w in words]
    items.sort(key=lambda x: x["text"].lower())
    return {"key": key, "type": "categorize", "difficulty": d, "est_seconds": 60,
            "payload": {"prompt": prompt, "items": items, "buckets": bl, "explain": explain,
                        "hints": [{"level": 1, "text": hint}]},
            "answer": {"buckets": ans}}


def pu(key, d, sentence, commas, explain, hint, prompt="Поставь запятые: нажми на место между словами"):
    """punctuation: words — слова без запятых; commas — индексы слов, ПОСЛЕ которых нужна запятая."""
    return {"key": key, "type": "punctuation", "difficulty": d, "est_seconds": 45,
            "payload": {"prompt": prompt, "words": sentence.split(), "explain": explain,
                        "hints": [{"level": 1, "text": hint}]},
            "answer": {"commas": commas}}


def tiles(key, d, prompt, word, explain):
    return {"key": key, "type": "letter_tiles", "difficulty": d, "est_seconds": 40,
            "payload": {"prompt": prompt, "letters": list(word), "explain": explain,
                        "hints": [{"level": 1, "text": f"В слове {len(word)} букв. Первая — «{word[0]}»."}]},
            "answer": {"value": word}}


def skill(key, title, rule, ex_title, steps, exercises, prereq=()):
    return {"key": key, "title": title, "rule_card": rule,
            "worked_example": {"title": ex_title, "steps": steps},
            "prerequisites": list(prereq), "exercises": exercises}


