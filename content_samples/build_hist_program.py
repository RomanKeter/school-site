def meta(explain: str, hint: str) -> dict:
    return {
        "explain": explain,
        "hints": [{"level": 1, "text": hint}],
        "solution_steps": [explain],
    }


def sc(prompt, options, correct, explain, hint, diff=1):
    opts = [{"id": f"o{i}", "text": t} for i, t in enumerate(options)]
    return {
        "type": "single_choice",
        "difficulty": diff,
        "est_seconds": 30 if diff < 3 else 45,
        "payload": {"prompt": prompt, "options": opts, **meta(explain, hint)},
        "answer": {"correct": [f"o{correct}"]},
    }


def fbc(prompt, options, correct, explain, hint, diff=1):
    letters = "abcdef"
    opts = [{"id": letters[i], "text": t} for i, t in enumerate(options)]
    return {
        "type": "fill_blank_choice",
        "difficulty": diff,
        "est_seconds": 30,
        "payload": {"prompt": prompt, "options": opts, **meta(explain, hint)},
        "answer": {"correct": [letters[correct]]},
    }


def txt(prompt, value, explain, hint, accept=None, diff=1):
    acc = list(accept or [value])
    if value not in acc:
        acc.insert(0, value)
    return {
        "type": "text_input",
        "difficulty": diff,
        "est_seconds": 40,
        "payload": {"prompt": prompt, **meta(explain, hint)},
        "answer": {"value": value, "accept": acc},
    }


def num(prompt, value, explain, hint, diff=1):
    return {
        "type": "number_input",
        "difficulty": diff,
        "est_seconds": 40,
        "payload": {"prompt": prompt, **meta(explain, hint)},
        "answer": {"value": value},
    }


def match(prompt, pairs, explain, hint, diff=2):
    """pairs: list[(left, right)]."""
    left = [{"id": f"l{i}", "text": a} for i, (a, _) in enumerate(pairs)]
    right = [{"id": f"r{i}", "text": b} for i, (_, b) in enumerate(pairs)]
    return {
        "type": "matching",
        "difficulty": diff,
        "est_seconds": 60,
        "payload": {"prompt": prompt, "left": left, "right": right, **meta(explain, hint)},
        "answer": {"pairs": {f"l{i}": f"r{i}" for i in range(len(pairs))}},
    }


def cats(prompt, buckets, items, explain, hint, diff=2):
    """buckets: list[(id, title)]; items: list[(id, text, bucket_id)]."""
    buck = {b: [] for b, _ in buckets}
    payload_items = []
    for iid, text, bid in items:
        payload_items.append({"id": iid, "text": text})
        buck[bid].append(iid)
    return {
        "type": "categorize",
        "difficulty": diff,
        "est_seconds": 60,
        "payload": {
            "prompt": prompt,
            "items": payload_items,
            "buckets": [{"id": b, "title": t} for b, t in buckets],
            **meta(explain, hint),
        },
        "answer": {"buckets": buck},
    }


def order(prompt, items, explain, hint, diff=2):
    """items: list[(id, text)] already in correct order."""
    return {
        "type": "drag_order",
        "difficulty": diff,
        "est_seconds": 50,
        "payload": {
            "prompt": prompt,
            "items": [{"id": i, "text": t} for i, t in items],
            **meta(explain, hint),
        },
        "answer": {"order": [i for i, _ in items]},
    }


def skill(key, title, rule, ex_title, steps, exercises, abbr, prereq=None):
    assert len(exercises) == 15, f"{key}: {len(exercises)} != 15"
    out = []
    for i, e in enumerate(exercises, 1):
        e = dict(e)
        e["key"] = f"hist.{abbr}.ex{i}"
        out.append(e)
    return {
        "key": key,
        "title": title,
        "rule_card": rule,
        "worked_example": {"title": ex_title, "steps": steps},
        "prerequisites": prereq or [],
        "exercises": out,
    }


def topic(key, title, skills, refs, synonyms, keywords, order, badge=""):
    return {
        "key": key,
        "title": title,
        "order": order,
        "textbook_refs": refs,
        "synonyms": synonyms,
        "keywords": keywords,
        "badge_code": badge,
        "skills": skills,
    }


def unit(key, title, quarter, order, topics):
    return {
        "format_version": 1,
        "subject": "hist",
        "unit": {"key": key, "title": title, "grade": 5, "quarter": quarter, "order": order},
        "topics": topics,
    }


