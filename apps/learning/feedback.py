"""Банк фраз без стыда (DS-25…DS-27)."""
import random

PHRASES = {
    "correct_first": ["Точно!", "В яблочко!", "Здорово получилось!", "Так держать!", "Отлично!"],
    "correct_retry": [
        "Ты нашла ошибку и исправила — вот так и учатся!",
        "Упорство победило!",
        "Видишь, получилось!",
    ],
    "almost": [
        "Почти! Давай посмотрим ещё раз.",
        "Хорошая попытка. Проверь ещё раз.",
        "Ты на верном пути — попробуй иначе.",
    ],
    "solution": [
        "Задача с подвохом. Посмотри разбор — завтра она станет твоей!",
        "Давай разберём вместе. Потом обязательно получится!",
    ],
    "hint": ["Попросить подсказку — умный ход!", "Подсказка рядом — это нормально."],
}


def phrase(kind: str) -> str:
    return random.choice(PHRASES.get(kind, ["Продолжай!"]))
